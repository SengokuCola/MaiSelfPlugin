"""Generate standalone sidebar pages from the shared HTML source.

Run with `uv run --no-sync python plugins/mai_recog_self/webui/build.py`
after editing index.html. No Node tooling or host changes are required.
"""

from pathlib import Path
import re


PAGES = ("images", "training", "models", "test", "environment")


def build() -> None:
    directory = Path(__file__).resolve().parent
    source = (directory / "index.html").read_text(encoding="utf-8")
    marker = "const HOME_PAGE = 'images';"
    if source.count(marker) != 1:
        raise ValueError("Expected exactly one HOME_PAGE marker in index.html")
    for page_id in PAGES:
        document = source.replace(marker, f"const HOME_PAGE = '{page_id}';")
        # Show the correct section before the asynchronous SDK handshake completes.
        document = re.sub(
            r'(<section class="section" id="([^"]+)"[^>]*)(>)',
            lambda match: match[1].replace(" hidden", "")
            + (" hidden" if match[2] != page_id else "") + match[3],
            document,
        )
        document = document.replace(
            "<!doctype html>",
            "<!doctype html>\n<!-- Generated by webui/build.py; edit webui/index.html. -->",
            1,
        )
        (directory / f"{page_id}.html").write_text(document, encoding="utf-8")


if __name__ == "__main__":
    build()
